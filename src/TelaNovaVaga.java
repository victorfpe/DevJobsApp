    private void PublicaVagaBotao1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_PublicaVagaBotao1ActionPerformed
        Vaga vaga = new Vaga();

vaga.setIdEmpresa(empresaLogada.getIdEmpresa());
vaga.setTitulo(txtCampoCargo.getText());
vaga.setDescricao(txtDescrisao.getText());
vaga.setSalario(Double.parseDouble(txtSalario.getText()));
vaga.setNivel(txtNivel.getSelectedItem().toString());
vaga.setModalidade(txtModalidade.getSelectedItem().toString());
vaga.setLocalizacao(empresaLogada.getCidade() + " - " + empresaLogada.getUf());

VagaDao dao = new VagaDao();

if (dao.inserir(vaga)) {
    JOptionPane.showMessageDialog(this, "Vaga publicada com sucesso!");

    TelaPerfilEmpresa tela = new TelaPerfilEmpresa(empresaLogada);
    tela.setLocationRelativeTo(null);
    tela.setVisible(true);
    this.dispose();
} else {
    JOptionPane.showMessageDialog(this, "Erro ao publicar vaga.");
    }//GEN-LAST:event_PublicaVagaBotao1ActionPerformed

    }
