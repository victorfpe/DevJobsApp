private void animarRolagem(int destino) {

    if (timerRolagem != null && timerRolagem.isRunning()) {
        timerRolagem.stop();
    }

    timerRolagem = new javax.swing.Timer(10, e -> {

        int atual = jPainelFundo.getY();
        int posicaoInicial = 80;
        int posicaoFinal = posicaoInicial - destino;

        int diferenca = posicaoFinal - atual;

        if (Math.abs(diferenca) <= 2) {

            jPainelFundo.setLocation(
                jPainelFundo.getX(),
                posicaoFinal
            );

            timerRolagem.stop();

        } else {

            int movimento = (int) (diferenca * 0.20);

            if (movimento == 0) {
                movimento = diferenca > 0 ? 1 : -1;
            }

            jPainelFundo.setLocation(
                jPainelFundo.getX(),
                atual + movimento
            );
        }
    });

    timerRolagem.start();
}


